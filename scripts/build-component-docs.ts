/**
 * Generates docs/components.md from the source: every exported component, its JSDoc (which carries
 * the Figma description and link) and the props declared by Startline (inherited HTML props omitted).
 * Run: npm run docs   — never edit docs/components.md by hand.
 */
import { writeFileSync } from "node:fs";
import { resolve, dirname, relative } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const entry = resolve(root, "src/index.ts");
const program = ts.createProgram([entry], {
  jsx: ts.JsxEmit.ReactJSX,
  module: ts.ModuleKind.ESNext,
  moduleResolution: ts.ModuleResolutionKind.Bundler,
  target: ts.ScriptTarget.ES2022,
  strict: true,
  skipLibCheck: true,
  baseUrl: root,
  paths: { "@/*": ["src/*"] },
});
const checker = program.getTypeChecker();
const mod = checker.getSymbolAtLocation(program.getSourceFile(entry)!)!;
const exports = checker.getExportsOfModule(mod);

const doc = (s: ts.Symbol) => ts.displayPartsToString(s.getDocumentationComment(checker)).trim();
const tags = (s: ts.Symbol) => Object.fromEntries(s.getJsDocTags(checker).map((t) => [t.name, ts.displayPartsToString(t.text).trim()]));
const esc = (s: string) => s.replace(/\|/g, "\\|").replace(/\n+/g, " ");
const isOwn = (p: ts.Symbol) => (p.declarations ?? []).some((d) => d.getSourceFile().fileName.startsWith(resolve(root, "src")));

const sections: string[] = [];
const index: string[] = [];
for (const sym of exports) {
  const name = sym.getName();
  if (!/^[A-Z]/.test(name) || name.endsWith("Props") || ["ICON_NAMES"].includes(name)) continue;
  const target = sym.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(sym) : sym;
  const decl = target.valueDeclaration;
  if (!decl) continue;
  const props = exports.find((e) => e.getName() === `${name}Props`);
  if (!props) continue; // only components
  const propsType = checker.getDeclaredTypeOfSymbol(props.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(props) : props);
  const file = relative(root, decl.getSourceFile().fileName);
  const { example, ...restTags } = tags(target);
  void restTags;
  const rows = propsType
    .getProperties()
    .filter(isOwn)
    .map((p) => {
      const d = p.valueDeclaration ?? p.declarations?.[0];
      const type = d ? checker.typeToString(checker.getTypeOfSymbolAtLocation(p, d), undefined, ts.TypeFormatFlags.NoTruncation) : "";
      const optional = (p.flags & ts.SymbolFlags.Optional) !== 0;
      const t = tags(p);
      return `| \`${p.getName()}\`${optional ? "" : " *"} | \`${esc(type.replace(/ \| undefined$/, ""))}\` | ${t.default ? `\`${esc(t.default)}\`` : ""} | ${esc(doc(p))} |`;
    });
  index.push(`- [${name}](#${name.toLowerCase()}) — ${esc(doc(target).replace(/\n/g, " ").split(/\.\s/)[0] ?? "")}`);
  sections.push(
    [
      `## ${name}`,
      "",
      doc(target),
      "",
      `Source: \`${file}\``,
      "",
      rows.length ? "| Prop | Type | Default | Description |\n|---|---|---|---|\n" + rows.join("\n") : "_No Startline-specific props._",
      "",
      "Also accepts the standard HTML attributes of its root element (`className`, `id`, `aria-*`, events…).",
      example ? `\n\`\`\`tsx\n${example.replace(/^\s*\n/, "")}\n\`\`\`` : "",
    ].join("\n"),
  );
}

const md = `<!-- GENERATED by scripts/build-component-docs.ts from the component source — do not edit. -->
# Startline components

\`import { … } from "@startline/ui"\` · * = required prop · Full rules: [CLAUDE.md](../CLAUDE.md) · Tokens: [tokens.md](tokens.md)

${index.join("\n")}

${sections.join("\n\n---\n\n")}
`;
writeFileSync(resolve(root, "docs/components.md"), md);
console.log(`wrote docs/components.md (${sections.length} components)`);
